#!/usr/bin/env python3
"""Fail-closed human-reviewed gate. No downloader can call this to approve data.

A reviewer assertion must be supplied by a real authorized human, not generated by
an automated agent. This tool verifies evidence consistency, NOT human identity or
cryptographic authorship. Exact-only QC is intentionally insufficient.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
from urllib.parse import urlsplit

REQUIRED = ['canonical_assay_id', 'assay_doi_or_accession', 'raw_file', 'sha256',
    'release_version', 'source_url', 'rights_decision', 'rights_proof_url',
    'raw_provenance', 'assay_identity_report', 'qc_report', 'dedup_report',
    'leakage_report', 'split_manifest', 'rights_report', 'human_reviewer',
    'human_review_approved', 'requested_tier']
REPORT_STATES = {
    'assay_identity_report': 'PASS_ASSAY_IDENTITY',
    'qc_report': 'PASS_ASSAY_QC',
    'dedup_report': 'PASS_OBSERVATION_DEDUP',
    'leakage_report': 'PASS_GROUP_AND_CROSS_BENCHMARK_LEAKAGE',
    'split_manifest': 'PASS_SPLIT_REVIEW',
    'rights_report': 'PASS_RIGHTS_REVIEW',
}
SENTINELS = {'UNKNOWN', 'NOT_VERIFIED', 'NOT_PINNED', 'PENDING', 'NONE', 'N/A'}


def file_hash(path):
    digest = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def evaluate(data, base=Path('.')):
    problems = []
    for key in REQUIRED:
        value = data.get(key)
        if not value or (isinstance(value, str) and value.strip().upper() in SENTINELS):
            problems.append('MISSING_OR_UNVERIFIED:' + key)
    expected = data.get('sha256', '')
    if not isinstance(expected, str) or not re.fullmatch('[0-9a-f]{64}', expected):
        problems.append('INVALID_SHA256')
    if data.get('rights_decision') not in ('APPROVED_FOR_BENCHMARK_ONLY', 'APPROVED_FOR_REDISTRIBUTION'):
        problems.append('RIGHTS_NOT_APPROVED')
    if data.get('human_review_approved') is not True:
        problems.append('NOT_HUMAN_APPROVED')
    if data.get('requested_tier') not in ('ADMITTED_CORE', 'ADMITTED_EXTENDED', 'SECONDARY_PROXY'):
        problems.append('INVALID_REQUESTED_TIER')
    for key in ('source_url', 'rights_proof_url'):
        url = urlsplit(data.get(key) or '')
        if url.scheme != 'https' or not url.hostname or url.username or url.password:
            problems.append('INVALID_PUBLIC_URL:' + key)
    raw = data.get('raw_file')
    if raw:
        path = base / raw
        if not path.is_file():
            problems.append('RAW_FILE_NOT_FOUND')
        elif file_hash(path) != expected:
            problems.append('RAW_FILE_HASH_MISMATCH')
    for key, required_state in REPORT_STATES.items():
        if not data.get(key):
            continue
        path = base / data[key]
        try:
            report = json.loads(path.read_text(encoding='utf-8'))
            if report.get('admission_gate_pass') is not True or report.get('state') != required_state:
                problems.append('EVIDENCE_NOT_FULL_PASS:' + key)
            if report.get('canonical_assay_id') != data.get('canonical_assay_id'):
                problems.append('EVIDENCE_ASSAY_MISMATCH:' + key)
            if report.get('source_sha256') != expected:
                problems.append('EVIDENCE_HASH_MISMATCH:' + key)
        except (OSError, ValueError, UnicodeDecodeError, AttributeError):
            problems.append('INVALID_OR_MISSING_JSON_EVIDENCE:' + key)
    if data.get('raw_provenance'):
        try:
            provenance = json.loads((base / data['raw_provenance']).read_text())
            if provenance.get('sha256') != expected:
                problems.append('PROVENANCE_HASH_MISMATCH')
            if provenance.get('bytes', 0) <= 0:
                problems.append('PROVENANCE_NO_RAW_BYTES')
        except (OSError, ValueError, AttributeError, TypeError):
            problems.append('INVALID_RAW_PROVENANCE')
    return {'canonical_assay_id': data.get('canonical_assay_id'),
            'state': data['requested_tier'] if not problems else 'HOLD_REVIEW',
            'admitted': not problems and data.get('requested_tier', '').startswith('ADMITTED_'),
            'issues': sorted(set(problems)),
            'reviewer_identity_cryptographically_verified': False}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--evidence', type=Path, required=True)
    p.add_argument('--output', type=Path)
    args = p.parse_args()
    data = json.loads(args.evidence.read_text(encoding='utf-8'))
    result = evaluate(data, args.evidence.parent)
    text = json.dumps(result, ensure_ascii=False, indent=2) + '\n'
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding='utf-8')
    print(text, end='')
    raise SystemExit(2 if result['issues'] else 0)


if __name__ == '__main__':
    main()
